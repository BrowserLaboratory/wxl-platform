# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

CHECKS_DIR = SKILL_ROOT / "checks"
MUTATORS_DIR = SKILL_ROOT / "mutators"
PROMPTS_DIR = SKILL_ROOT / "prompts"
SCHEMA_DIR = SKILL_ROOT / "schemas"

# Canonical 14-check inventory. The CLI invokes ``python <check>.py`` per
# entry; ordering is alphabetical-by-family but locked here for stability
# across runs (the spec calls it the "fourteen deterministic Preflight
# checks").
CHECK_INVENTORY: tuple[str, ...] = (
    "mainland_vocab",
    "placeholder_grep",
    "duplicate_sentences",
    "citation_format",
    "readability_metrics",
    "lazy_writer_check",
    "ai_tells",
    "burstiness",
    "hedge_density",
    "imperative_fog",
    "lexical_diversity",
    "pronoun_consistency",
    "discourse_marker_density",
    "repetition_fingerprint",
)

# Persona id -> prompt filename. The agents_disabled config key (and the
# project-config schema enum) uses the short id; the prompt files use the
# longer form for historical reasons. Keep the mapping centralized.
PERSONA_PROMPTS: dict[str, str] = {
    "sloppy": "sloppy_agent.md",
    "illogical": "illogical_agent.md",
    "shallow": "shallow_agent.md",
    "humanity": "humanity_auditor.md",
}

CHECK_SUBPROC_TIMEOUT_S = 60
FUZZ_SUBPROC_TIMEOUT_S = 600

# Minimal ``init-config`` stub. Validates against project-config.schema.json
# (every field is optional; this just sets ``profile: general``).
INIT_CONFIG_STUB = """# humane-prose-audit project config
# Generated by `audit_orchestrator.py init-config`.
# See humane-prose-audit/schemas/project-config.schema.json for the full
# option surface.
profile: general
"""


# ---------------------------------------------------------------------------
# Run-dir layout helpers
# ---------------------------------------------------------------------------


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def _read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _load_schema(name: str) -> dict:
    return _read_json(SCHEMA_DIR / f"{name}.schema.json")


def _validate(doc: Any, schema_name: str) -> list[str]:
    validator = Draft7Validator(_load_schema(schema_name))
    return [
        f"{'/'.join(str(p) for p in err.absolute_path) or '<root>'}: {err.message}"
        for err in sorted(
            validator.iter_errors(doc), key=lambda e: list(e.absolute_path)
        )
    ]


