#!/usr/bin/env python3
"""Five-phase humane-prose-audit orchestrator.

This script is the CLI entry point that drives the full audit pipeline
against a single Markdown target. The five phases run in fixed order:

  1. Preflight checks       (subprocess per check under ``checks/``)
  2. Sub-agent dispatch     (writes ``agents/_inputs.json``; no LLM call)
  3. Fuzz analysis          (subprocess to ``mutators/run_fuzz.py``)
  4. Humane-signal scoring  (``output_aggregator.compute_humane_score``)
  5. Consolidated findings  (``output_aggregator.aggregate``)

Each phase writes its output under ``<run_dir>/`` so the run is fully
inspectable on disk. The final ``audit-report.json`` validates against
``schemas/audit-report.schema.json`` — this is the task's primary
verification target.

LLM personas are *not* invoked here. Phase 2 only sets up an
``agents/_inputs.json`` describing what should be run; an external
harness drops sidecar JSON files into ``<run_dir>/agents/`` and the
orchestrator picks them up on the next ``--resume`` run.

CLI shapes::

    audit_orchestrator.py <target.md> --out <run-dir>
        [--seed <int>] [--phase <N>] [--no-fuzz]
        [--config <path>] [--resume]

    audit_orchestrator.py init-config [--profile <name>] [--force]

See ``openspec/changes/humane-prose-audit-refactor/specs/
humane-prose-audit-core/spec.md`` -> "Five-phase audit workflow" for
the spec contract, especially the "Preflight Critical short-circuit"
scenario implemented in Phase 1 -> Phase 2/3 gating below.
"""
