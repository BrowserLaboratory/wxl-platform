#!/usr/bin/env python3
"""Scaffold generator for new humane-prose-audit checks.

Given a snake_case ``--name``, materialise three files in one shot:

  1. ``humane-prose-audit/checks/<name>.py``        — Python check skeleton
  2. ``humane-prose-audit/rationales/<name>.md``    — rationale stub
  3. ``humane-prose-audit/tests/test_<name>.py``    — pytest stub

The generated check returns ``([], {'placeholder': True})`` so its JSON
output is trivially schema-valid and the new test stub passes on day one.
Future maintainers can grep for ``TODO: implement <name> detection`` to
find scaffolds that still need real logic.

CLI:
  new_check_scaffold.py --name <name> [--dry-run]
                        [--checks-dir DIR] [--rationales-dir DIR]
                        [--tests-dir DIR] [--force]

The ``--*-dir`` overrides (and matching ``HPA_*_DIR`` env vars) let tests
materialise scaffolds into ``tmp_path`` without polluting the real skill
tree.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

SKILL_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CHECKS_DIR = SKILL_ROOT / "checks"
DEFAULT_RATIONALES_DIR = SKILL_ROOT / "rationales"
DEFAULT_TESTS_DIR = SKILL_ROOT / "tests"

NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")

# Phase E audit Lens 1 [Medium]: Names matching the regex but colliding with
# Python stdlib or commonly imported packages would shadow them whenever a
# co-located script in checks/ does `import <name>`. The denylist keeps
# scaffold output portable.
import keyword as _keyword
RESERVED_NAMES = frozenset({
    "os", "sys", "json", "io", "re", "time", "subprocess", "pathlib",
    "typing", "argparse", "abc", "ast", "collections", "contextlib", "copy",
    "csv", "dataclasses", "datetime", "enum", "functools", "glob", "hashlib",
    "itertools", "logging", "math", "random", "shutil", "string", "tempfile",
    "threading", "uuid", "warnings",
    # third-party deps used inside humane-prose-audit:
    "yaml", "jsonschema", "tiktoken", "pytest",
    # in-skill module names worth protecting:
    "config", "schemas", "scripts", "checks", "mutators", "prompts", "tests",
    "rationales", "wiki",
})


def _is_reserved(name: str) -> bool:
    return name in RESERVED_NAMES or _keyword.iskeyword(name)


def _check_template(name: str) -> str:
    return f'''#!/usr/bin/env python3
"""{name} check (scaffold).

TODO: implement {name} detection.

This is a placeholder generated by ``scripts/new_check_scaffold.py``.
Replace ``compute`` with real detection logic and update the rationale
under ``rationales/{name}.md`` before promoting this check to production.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

SKILL_ROOT = Path(__file__).resolve().parent.parent


def compute(text: str) -> tuple[list[dict], dict]:
    """Return ``(findings, metadata)`` for ``text``.

    Placeholder implementation — always returns no findings. Real checks
    should emit findings with lowercase severity values such as ``"low"``,
    ``"medium"``, or ``"high"`` and populate metadata with the numbers the
    rationale cites.
    """
    _ = text  # silence unused warnings in the scaffold
    return [], {{"placeholder": True}}


def compute_findings(text: str) -> list[dict]:
    """Back-compat shim returning just the findings list."""
    findings, _ = compute(text)
    return findings


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="{name} check (scaffold)")
    parser.add_argument("target", help="Path to file to scan")
    args = parser.parse_args(argv)

    target = Path(args.target)
    if not target.exists() or not target.is_file():
        print(
            json.dumps({{"error": f"target not found: {{target}}"}}, ensure_ascii=False),
            file=sys.stderr,
        )
        return 2

    try:
        text = target.read_text(encoding="utf-8", errors="replace")
    except OSError as exc:
        print(
            json.dumps({{"error": f"cannot read target: {{exc}}"}}, ensure_ascii=False),
            file=sys.stderr,
        )
        return 2

    findings, metadata = compute(text)
    print(
        json.dumps(
            {{
                "check": "{name}",
                "target": str(target.resolve()),
                "findings": findings,
                "metadata": metadata,
            }},
            ensure_ascii=False,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
'''


def _rationale_template(name: str) -> str:
    return f"""# {name} — Rationale

## What
TODO: describe what this check detects.

## Threshold
TODO: cite concrete threshold(s).

## Why
TODO: empirical / theoretical justification.

## Limitations
TODO: false positives, scope, brittleness notes.
"""


def _test_template(name: str) -> str:
    return f'''"""Tests for humane-prose-audit/checks/{name}.py (scaffold).

Auto-generated by ``scripts/new_check_scaffold.py``. The smoke test below
exercises the CLI against a known-clean fixture. Replace the ``xfail`` stub
with real semantic assertions once the check is implemented.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

SKILL_ROOT = Path(__file__).resolve().parent.parent
CHECKS_DIR = SKILL_ROOT / "checks"
FIXTURES_DIR = SKILL_ROOT / "tests" / "fixtures"


def test_{name}_smoke():
    target = FIXTURES_DIR / "human-flavored.md"
    proc = subprocess.run(
        [sys.executable, str(CHECKS_DIR / "{name}.py"), str(target)],
        capture_output=True,
        text=True,
    )
    assert proc.returncode == 0, proc.stderr
    payload = json.loads(proc.stdout)
    assert payload["check"] == "{name}"
    assert "findings" in payload
    assert "target" in payload


@pytest.mark.xfail(reason="TODO: implement real assertions for {name}")
def test_{name}_real_semantics():
    # Replace this stub with detection assertions once {name} is implemented.
    raise AssertionError("not yet implemented")
'''


def _planned_paths(
    name: str,
    checks_dir: Path,
    rationales_dir: Path,
    tests_dir: Path,
) -> tuple[Path, Path, Path]:
    return (
        checks_dir / f"{name}.py",
        rationales_dir / f"{name}.md",
        tests_dir / f"test_{name}.py",
    )


def _resolve_dirs(args: argparse.Namespace) -> tuple[Path, Path, Path]:
    checks = (
        Path(args.checks_dir)
        if args.checks_dir is not None
        else Path(os.environ.get("HPA_CHECKS_DIR", DEFAULT_CHECKS_DIR))
    )
    rationales = (
        Path(args.rationales_dir)
        if args.rationales_dir is not None
        else Path(os.environ.get("HPA_RATIONALES_DIR", DEFAULT_RATIONALES_DIR))
    )
    tests = (
        Path(args.tests_dir)
        if args.tests_dir is not None
        else Path(os.environ.get("HPA_TESTS_DIR", DEFAULT_TESTS_DIR))
    )
    return checks, rationales, tests


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description="Generate a new humane-prose-audit check scaffold "
                    "(check.py + rationale.md + test stub)."
    )
    parser.add_argument(
        "--name",
        required=True,
        help="Snake_case check name (must match ^[a-z][a-z0-9_]*$).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the three planned paths and exit without writing.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing files. Off by default to keep the tool idempotent-safe.",
    )
    parser.add_argument("--checks-dir", default=None, help="Override checks/ output directory.")
    parser.add_argument("--rationales-dir", default=None, help="Override rationales/ output directory.")
    parser.add_argument("--tests-dir", default=None, help="Override tests/ output directory.")
    args = parser.parse_args(argv)

    name: str = args.name
    if not NAME_RE.match(name):
        print(
            f"error: --name {name!r} is invalid; must match regex ^[a-z][a-z0-9_]*$ "
            f"(lowercase snake_case, starts with a letter).",
            file=sys.stderr,
        )
        return 2
    if _is_reserved(name):
        print(
            f"error: --name {name!r} is a reserved Python module name or keyword; "
            f"scaffolding it would shadow stdlib / packaged imports.",
            file=sys.stderr,
        )
        return 2

    checks_dir, rationales_dir, tests_dir = _resolve_dirs(args)
    check_path, rationale_path, test_path = _planned_paths(
        name, checks_dir, rationales_dir, tests_dir
    )

    if args.dry_run:
        print(str(check_path))
        print(str(rationale_path))
        print(str(test_path))
        return 0

    # Idempotent-safe: refuse to overwrite unless --force.
    if not args.force:
        conflicts = [p for p in (check_path, rationale_path, test_path) if p.exists()]
        if conflicts:
            for p in conflicts:
                print(f"error: target already exists: {p}", file=sys.stderr)
            print(
                "refusing to overwrite without --force; "
                "delete the conflicting files or pick a new --name.",
                file=sys.stderr,
            )
            return 1

    # Ensure parent directories exist (so override dirs work in tmp_path).
    for parent in {check_path.parent, rationale_path.parent, test_path.parent}:
        parent.mkdir(parents=True, exist_ok=True)

    check_path.write_text(_check_template(name), encoding="utf-8")
    rationale_path.write_text(_rationale_template(name), encoding="utf-8")
    test_path.write_text(_test_template(name), encoding="utf-8")

    print(f"created: {check_path}")
    print(f"created: {rationale_path}")
    print(f"created: {test_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
