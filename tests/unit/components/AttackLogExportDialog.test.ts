import { describe, it, expect, vi } from 'vitest'
import { mount, flushPromises } from '@vue/test-utils'
import Dialog from '../../../.vitepress/theme/components/AttackLogExportDialog.vue'

describe('Attack log export dialog', () => {
  it('defaults to full JSON and closes after generation completes', async () => {
    const generate = vi.fn().mockResolvedValue(undefined)
    const wrapper = mount(Dialog, { props: { generate } })
    await wrapper.find('form').trigger('submit')
    await flushPromises()
    expect(generate).toHaveBeenCalledWith({ format: 'json', mode: 'full', identity: { name: '', className: '' } })
    expect(wrapper.emitted('close')).toHaveLength(1)
    wrapper.unmount()
  })
  it('passes selected options, blocks duplicate submission and cancellation while pending', async () => {
    let finish!: () => void
    const generate = vi.fn(() => new Promise<void>(resolve => { finish = resolve }))
    const wrapper = mount(Dialog, { props: { generate } })
    await wrapper.find('[data-export-format]').setValue('markdown')
    await wrapper.find('[data-export-mode]').setValue('thinned')
    await wrapper.find('[data-export-name]').setValue('小明')
    await wrapper.find('[data-export-class]').setValue('二甲')
    await wrapper.find('form').trigger('submit')
    await wrapper.find('form').trigger('submit')
    await wrapper.find('dialog').trigger('cancel')
    expect(generate).toHaveBeenCalledTimes(1)
    expect(generate).toHaveBeenCalledWith({ format: 'markdown', mode: 'thinned', identity: { name: '小明', className: '二甲' } })
    expect(wrapper.find('fieldset').attributes('disabled')).toBeDefined()
    expect(wrapper.emitted('close')).toBeUndefined()
    finish()
    await flushPromises()
    expect(wrapper.emitted('close')).toHaveLength(1)
    wrapper.unmount()
  })
  it('shows a failure, retains choices and allows retry', async () => {
    const generate = vi.fn().mockRejectedValueOnce(new Error('digest failed')).mockResolvedValueOnce(undefined)
    const wrapper = mount(Dialog, { props: { generate } })
    await wrapper.find('[data-export-name]').setValue('小明')
    await wrapper.find('form').trigger('submit')
    await flushPromises()
    expect(wrapper.find('[role="alert"]').text()).toContain('重試')
    expect(wrapper.emitted('close')).toBeUndefined()
    expect(wrapper.find('fieldset').attributes('disabled')).toBeUndefined()
    await wrapper.find('form').trigger('submit')
    await flushPromises()
    expect(generate).toHaveBeenLastCalledWith(expect.objectContaining({ identity: { name: '小明', className: '' } }))
    expect(wrapper.emitted('close')).toHaveLength(1)
    wrapper.unmount()
  })
  it('cancels without generating and a new dialog has empty identity', async () => {
    const generate = vi.fn()
    const wrapper = mount(Dialog, { props: { generate } })
    await wrapper.find('[data-export-name]').setValue('小明')
    await wrapper.find('[data-export-cancel]').trigger('click')
    expect(wrapper.emitted('close')).toHaveLength(1)
    expect(generate).not.toHaveBeenCalled()
    wrapper.unmount()
    const fresh = mount(Dialog, { props: { generate } })
    expect((fresh.find('[data-export-name]').element as HTMLInputElement).value).toBe('')
    fresh.unmount()
  })
})
